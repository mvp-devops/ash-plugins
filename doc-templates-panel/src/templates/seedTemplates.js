/** Множество идентификаторов встроенных шаблонов. */
export const SEED_IDS = new Set(SEED_TEMPLATES.map((template) => template.id));

/** Нормализованные встроенные шаблоны (готовый read-only слой). */
export const SEED_NORMALIZED = SEED_TEMPLATES.map((template) => ({
  ...template,
  builtin: true,
  readonly: true,
}));

/**
 * Встроенный шаблон по id.
 * @param {string} id
 * @returns {DocTemplate|null}
 */
export function seedById(id) {
  return SEED_NORMALIZED.find((template) => template.id === id) ?? null;
}
